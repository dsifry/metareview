func TestResolveTopTrims(t *testing.T) {
	root, _ := newRepoBytes(t, map[string][]byte{"a.go": []byte("package a\n")})
	top, err := resolveTop(root, realGit)
	if err != nil || top != root && !strings.HasPrefix(top, root) {
		// macOS may resolve /var -> /private/var; accept either the temp dir or its eval.
		if err != nil {
			t.Fatal(err)
		}
	}
	if top == "" {
		t.Fatal("empty top")
	}
	if _, err := os.Stat(filepath.Join(top, "a.go")); err != nil {
		t.Fatal(err)
	}
}
