func TestParseTree(t *testing.T) {
	in := []byte("\x00100644 blob abc\tfile.go\x00120000 blob def\tlink\x00160000 commit zzz\tsub\x00100644 blob hash\t\x00")
	paths, err := parseTree(in)
	if err != nil {
		t.Fatal(err)
	}
	if !reflect.DeepEqual(paths, []treeBlob{{path: "file.go", id: "abc"}, {path: "link", id: "def"}}) {
		t.Fatalf("%v", paths)
	}
	if _, err := parseTree([]byte("no-tab\x00")); err == nil {
		t.Fatal("expected bad record")
	}
	if _, err := parseTree([]byte("only\tpath\x00")); err == nil {
		t.Fatal("expected bad meta")
	}
}

func TestParseBatch(t *testing.T) {
	body := []byte("hello")
	var buf bytes.Buffer
	buf.WriteString("abc blob 5\n")
	buf.Write(body)
	buf.WriteByte('\n')
	got, err := parseBatch(buf.Bytes(), []string{"a.go"})
	if err != nil || !bytes.Equal(got["a.go"], body) {
		t.Fatalf("%v %q", err, got["a.go"])
	}
	empty, err := parseBatch([]byte("abc blob 0\n\n"), []string{"e.go"})
	if err != nil || len(empty["e.go"]) != 0 {
		t.Fatalf("empty: %v %q", err, empty["e.go"])
	}
	if _, err := parseBatch(nil, []string{"a"}); err == nil {
		t.Fatal("short header")
	}
	if _, err := parseBatch([]byte("abc missing\n"), []string{"a"}); err == nil {
		t.Fatal("missing blob")
	}
	if _, err := parseBatch([]byte("abc blob zz\n"), []string{"a"}); err == nil {
		t.Fatal("bad size")
	}
	if _, err := parseBatch([]byte("abc blob 1\nXY"), []string{"a"}); err == nil {
		t.Fatal("missing newline")
	}
	if _, err := parseBatch([]byte("abc blob -1\n"), []string{"a"}); err == nil {
		t.Fatal("negative size")
	}
}

