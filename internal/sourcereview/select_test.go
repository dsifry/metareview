func TestSelectEdges(t *testing.T) {
	files := map[string][]byte{
		"node_modules/x.go":    []byte("package x\n"),
		"third_party/y.go":     []byte("package y\n"),
		"internal/foo_test.go": []byte("package internal\n"),
		"fixtures/a.go":        []byte("package fixtures\nfunc A() {}\n"),
		"pkg/after_code.go":    []byte("package pkg\n// Code generated by x. DO NOT EDIT.\n"),
		"pkg/after_comment.go": []byte("\n// header\n// Code generated by x. DO NOT EDIT.\npackage pkg\n"),
		"pkg/block.go":         []byte("/*\n header\n*/\n// Code generated by x. DO NOT EDIT.\npackage pkg\n"),
		"pkg/code_block.go":    []byte("x := 1 /* comment\n*/\n// Code generated by x. DO NOT EDIT.\n"),
		"pkg/after_close.go":   []byte("/* c */ code\n// Code generated by x. DO NOT EDIT.\n"),
		"pkg/not_marker.go":    []byte("// Code generated by x. DO NOT EDIT. extra\npackage pkg\n"),
		"pkg/crlf.go":          []byte("// note\r\n// Code generated by x. DO NOT EDIT.\r\n"),
		"Gemfile.lock":         []byte("GEM\n"),
		"pkg/empty.go":         {},
		"pkg/nbsp.go":          []byte("\u00a0// comment\n世\n"),
	}
	root, _ := newRepoBytes(t, files)
	kept, dropped, _, err := Select(root, nil)
	if err != nil {
		t.Fatal(err)
	}
	wantKept := []string{"fixtures/a.go", "pkg/after_close.go", "pkg/after_code.go", "pkg/code_block.go", "pkg/empty.go", "pkg/nbsp.go", "pkg/not_marker.go"}
	var got []string
	for _, f := range kept {
		got = append(got, f.Path)
	}
	if !reflect.DeepEqual(got, wantKept) {
		t.Fatalf("kept %v\ndropped %v", got, dropped)
	}
}

func TestClassifyLine(t *testing.T) {
	cases := []struct {
		line    string
		in      bool
		comment bool
		still   bool
	}{
		{"", false, true, false},
		{"   \t", false, true, false},
		{"// hi", false, true, false},
		{"  // hi", false, true, false},
		{"code // hi", false, false, false},
		{"/* c */", false, true, false},
		{"/* c", false, true, true},
		{"still", true, true, true},
		{"*/", true, true, false},
		{"*/ code", true, false, false},
		{"code /* c", false, false, true},
		{"a /* b */ c", false, false, false},
		{"/* a */ // tail", false, true, false},
		{"/*/", false, true, true},
		{"/**/", false, true, false},
		{"世", false, false, false},
	}
	for _, tc := range cases {
		comment, still := classifyLine(tc.line, tc.in)
		if comment != tc.comment || still != tc.still {
			t.Errorf("%q in=%v -> comment=%v still=%v, want %v %v", tc.line, tc.in, comment, still, tc.comment, tc.still)
		}
	}
}

