func TestSelectGitCommandErrors(t *testing.T) {
	git := func(_ string, args []string, _ []byte) ([]byte, error) {
		switch args[0] {
		case "rev-parse":
			if args[1] == "--show-toplevel" {
				return []byte("/repo\n"), nil
			}
			return []byte("abc\n"), nil
		case "ls-tree":
			return nil, errors.New("ls-tree")
		default:
			return nil, errors.New("unexpected")
		}
	}
	if _, _, _, err := Select("/repo", git); err == nil {
		t.Fatal("ls-tree")
	}
	git = func(_ string, args []string, _ []byte) ([]byte, error) {
		switch args[0] {
		case "rev-parse":
			if args[1] == "--show-toplevel" {
				return []byte("/repo\n"), nil
			}
			return []byte("abc\n"), nil
		case "ls-tree":
			return []byte("100644 blob abc\ta.go\x00"), nil
		default:
			return nil, errors.New("cat-file")
		}
	}
	if _, _, _, err := Select("/repo", git); err == nil {
		t.Fatal("cat-file")
	}
}

